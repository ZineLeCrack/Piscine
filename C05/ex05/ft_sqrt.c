int	ft_sqrt(int nb)
{
	int	i;
	int	sq;

	i = 0;
	while (42)
	{
		sq = i * i;
		if (sq == nb)
			return (i);
		if (sq > nb)
			return (0);
		i++;
	}
	return (0);
}
