int	ft_isalpha(char c)
{
	return (('a' <= c && c <= 'z') || ('A' <= c && c <= 'Z'));
}

int	ft_str_is_alpha(char *str)
{
	if (!*str)
		return (1);
	return (ft_isalpha(*str) && ft_str_is_alpha(str + 1));
}
