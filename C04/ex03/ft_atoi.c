int	ft_atoi(char *str)
{
	int	i;
	int	sign;
	int	n;

	n = 0;
	i = 0;
	sign = 1;
	while (str[i] && (('\t' <= str[i] && str[i] <= '\r') || str[i] == ' '))
		i++;
	while (str[i] && (str[i] == '+' || str[i] == '-'))
		sign *= ((str[i++] != '-') * 2) - 1;
	while (str[i] && ('0' <= str[i] && str[i] <= '9'))
	{
		n *= 10;
		n += str[i++] - '0';
	}
	return (n * sign);
}
